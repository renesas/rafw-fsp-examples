extern bsp_leds_t g_bsp_leds;

void LED_LEDOnOff (bsp_led_t led, bsp_io_level_t led_level)
{
    bsp_leds_t leds = g_bsp_leds;
    g_gpio_w.p_api->pinWrite(g_gpio_w.p_ctrl, (bsp_io_port_pin_t) leds.p_leds[led], led_level);
}

