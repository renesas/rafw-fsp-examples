/*
 ******************************************************
 * Usage : declaration user instance, 
 * open -> read/write -> close, then open -> ... > close
 *******************************************************
 */
static fsp_err_t open_qspi(void);
static void close_qspi(void);

ospi_w_instance_ctrl_t user_ospi_ctrl;

/*******************************************************************************************************************//**
 * main() is generated by the FSP Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    fsp_err_t err = FSP_SUCCESS;
    uint8_t data_write[PAGE_WRITE_SIZE] = {RESET_VALUE,};
    uint8_t verify_written_data[PAGE_WRITE_SIZE] = {RESET_VALUE,};
    fsp_pack_version_t version = {RESET_VALUE};

    /* Version get API for FLEX pack information */
    R_FSP_VersionGet(&version);

    /* Example Project information printed on the Console */
    APP_PRINT(BANNER_1);
    APP_PRINT(BANNER_2);
    APP_PRINT(BANNER_3, EP_VERSION);
    APP_PRINT(BANNER_4, version.version_id_b.major, version.version_id_b.minor, version.version_id_b.patch);
    APP_PRINT(BANNER_5);
    APP_PRINT(BANNER_6);

    /* Open Flash_HP */
    err = open_qspi();
    if (FSP_SUCCESS != err)
    {
        APP_ERR_PRINT("Flah_HP_Open API failed\r\n");
        goto end_of_function;
    }

    /* Erase flash before writing */
    err = R_OSPI_W_Erase(&user_ospi_ctrl, QSPI_FLASH_ADDRESS(PAGE_FIRST),
    SECTOR_SIZE);
    if (FSP_SUCCESS != err)
    {
        APP_ERR_PRINT("R_OSPI_W_Erase Failed\r\n");
        APP_ERR_TRAP(err);
        goto close_module;
    }

    /* Fill the data write buffer further to be written in QSPI flash device */
    for (uint16_t write_index = RESET_VALUE; write_index < PAGE_WRITE_SIZE; write_index++)
    {
        data_write[write_index] = (uint8_t) write_index;
    }

#ifdef ENABLE_DATA_VERIFICATION_LOG
    APP_PRINT("\r\n data_write: %02X %02X %02X ...\r\n", data_write[0], data_write[1], data_write[2]);
#endif

    /* Write data to QSPI Flash */
    err = R_OSPI_W_Write(&user_ospi_ctrl, data_write, (uint8_t*) QSPI_FLASH_ADDRESS(PAGE_FIRST), PAGE_WRITE_SIZE);
    if (FSP_SUCCESS != err)
    {
        APP_ERR_PRINT("R_OSPI_W_Write Failed\r\n");
        APP_ERR_TRAP(err);
        goto close_module;
    }

    /* Read data from QSPI memory region */
    memcpy(verify_written_data, QSPI_FLASH_READ_ADDR(PAGE_FIRST), PAGE_WRITE_SIZE);

#ifdef ENABLE_DATA_VERIFICATION_LOG
    APP_PRINT("\r\n written_data: %02X %02X %02X ...\r\n",
              verify_written_data[0], verify_written_data[1], verify_written_data[2]);
#endif

    /* Verify the written data */
    if (FSP_SUCCESS == (fsp_err_t) (memcmp(verify_written_data, data_write, PAGE_WRITE_SIZE)))
    {
        APP_PRINT("\r\n ** Data read matches with written data ** \r\n");
    }
    else
    {
        APP_ERR_PRINT("\r\nQSPI operation Failed: not match with written data\r\n");
    }

    close_module :
    /* close QSPI module */
    close_qspi();

    end_of_function :
    APP_PRINT("\r\n ** demo ends here **\r\n\r\n");

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif
}

/*******************************************************************************************************************//**
 * This function is called at various points during the startup process.  This implementation uses:
 *  - the event that is called after the clocks have been configured, to freeze the watchdog
 *  - the event that is called right before main() to set up the pins
 *
 * @param[in]  event    Where at in the start up process the code is currently at
 **********************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
    }

    if (BSP_WARM_START_POST_CLOCK == event)
    {
        /* System clocks are configured. */

        /*
         * Freeze the watchdog, to avoid an unexpected reboot.
         * The watchdog-freeze setting must be enabled for this to have an effect.
         */
        R_BSP_PeripheralFreeze (BSP_FREEZE_PERIPHERAL_SYS_WDOG);
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup. */
        /* Configure pins. */
        R_GPIO_W_Open (&g_gpio_w_ctrl, &IOPORT_CFG_NAME);
    }
}

/*******************************************************************************************************************//**
 *  @brief       Open/Close QSPI module
 *  @param[IN]   spi_protocol mode
 *  @retval      None
 **********************************************************************************************************************/
static fsp_err_t open_qspi(void)
{
    fsp_err_t err = FSP_SUCCESS;

    APP_PRINT("\r\n ** Open QSPI module ** \r\n");

    /* Open Flash_HP */
    err = R_OSPI_W_Open(&user_ospi_ctrl, &g_qspi_cfg);

    /* Handle Error */
    if (FSP_SUCCESS != err)
    {
        APP_ERR_PRINT("R_OSPI_W_Open Failed\r\n");
    }

    return err;
}

static void close_qspi(void)
{
    fsp_err_t error = FSP_SUCCESS;

    APP_PRINT("\r\n ** Closing QSPI module ** \r\n");

    /* close QSPI module */
    error = R_OSPI_W_Close(&user_ospi_ctrl);
    if (FSP_SUCCESS != error)
    {
        APP_ERR_PRINT("R_OSPI_W_Close Failed\r\n");
    }
}

